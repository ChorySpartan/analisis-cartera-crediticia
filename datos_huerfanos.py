import pandas as pd

clientes = pd.read_csv('datos/clientes_limpio.csv')
prestamos = pd.read_csv('datos/prestamos.csv')

huerfanos = prestamos[~prestamos['cliente_id'].isin(clientes['cliente_id'])]
print(f"Préstamos con cliente_id huérfano:  {len(huerfanos)}")

pagos = pd.read_csv('datos/pagos.csv')

huerfanos_pagos = pagos[~pagos['prestamo_id'].isin(prestamos['prestamo_id'])]
print(f"Pagos con prestamo_id huérfano: {len(huerfanos_pagos)}")





























































































